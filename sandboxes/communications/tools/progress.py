#!/usr/bin/env python3
"""Build PROGRESS.md from every pack.yaml. Fail if --check and file is stale.

Uses a tiny YAML subset parser so this runs without PyYAML installed.
(Full PyYAML still fine if present.)
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "PROGRESS.md"


def parse_pack_yaml(text: str) -> dict:
    """Parse the simple pack.yaml shape used in this repo."""
    try:
        import yaml  # type: ignore

        data = yaml.safe_load(text) or {}
        if isinstance(data, dict):
            return data
    except Exception:
        pass

    data: dict = {}
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip() or line.lstrip().startswith("#"):
            i += 1
            continue
        m = re.match(r"^([A-Za-z0-9_]+):\s*(.*)$", line)
        if not m:
            i += 1
            continue
        key, raw = m.group(1), m.group(2).strip()
        if raw == "" or raw == "[]":
            # maybe a block list follows; our files use [] inline
            data[key] = [] if raw == "[]" else None
        elif raw == "null":
            data[key] = None
        elif re.fullmatch(r"-?\d+", raw):
            data[key] = int(raw)
        elif re.fullmatch(r"-?\d+\.\d+", raw):
            data[key] = float(raw)
        elif (raw.startswith('"') and raw.endswith('"')) or (
            raw.startswith("'") and raw.endswith("'")
        ):
            data[key] = raw[1:-1]
        elif raw.startswith("[") and raw.endswith("]"):
            inner = raw[1:-1].strip()
            if not inner:
                data[key] = []
            else:
                data[key] = [p.strip().strip("'\"") for p in inner.split(",")]
        else:
            # strip inline comments
            data[key] = re.split(r"\s+#", raw, maxsplit=1)[0].strip()
        i += 1
    return data


def load_packs() -> list[dict]:
    packs: list[dict] = []
    for path in sorted(ROOT.rglob("pack.yaml")):
        if "templates" in path.parts:
            continue
        data = parse_pack_yaml(path.read_text(encoding="utf-8"))
        data["_path"] = str(path.parent.relative_to(ROOT)).replace("\\", "/")
        packs.append(data)
    return packs


def render(packs: list[dict]) -> str:
    lines: list[str] = [
        "# Progress",
        "",
        "> Generated by `tools/progress.py`. Do not hand-edit.",
        "",
        "| Phase | Pack | Tier | Status | Confidence | Est. hours | Path |",
        "|------:|------|-----:|--------|------------|----------:|------|",
    ]
    by_phase: dict[int, list[dict]] = {}
    for p in packs:
        phase = int(p.get("phase") or 0)
        by_phase.setdefault(phase, []).append(p)
        lines.append(
            "| {phase} | {title} | {tier} | {status} | {conf} | {hours} | `{path}` |".format(
                phase=phase,
                title=p.get("title", p.get("id", "?")),
                tier=p.get("tier", ""),
                status=p.get("status", ""),
                conf="" if p.get("confidence") is None else p.get("confidence"),
                hours=p.get("est_hours", ""),
                path=p.get("_path", ""),
            )
        )

    lines += ["", "## Totals per phase", ""]
    lines += [
        "| Phase | Packs | Est. hours | Done |",
        "|------:|------:|----------:|-----:|",
    ]
    for phase in sorted(by_phase):
        group = by_phase[phase]
        hours = sum(float(p.get("est_hours") or 0) for p in group)
        done = sum(1 for p in group if p.get("status") == "done")
        lines.append(f"| {phase} | {len(group)} | {hours:g} | {done} |")

    lines += ["", "## VERIFY items", ""]
    any_verify = False
    for p in packs:
        for item in p.get("verify") or []:
            any_verify = True
            if isinstance(item, dict):
                text = item.get("item", "")
                loc = item.get("location", "")
                lines.append(
                    f"- [`{p.get('_path')}`] {text}" + (f" — {loc}" if loc else "")
                )
            else:
                lines.append(f"- [`{p.get('_path')}`] {item}")
    if not any_verify:
        lines.append(
            "_None listed in pack.yaml yet (see worksheets / "
            "`00-interview-prep/VERIFY.legacy.md`)._"
        )

    lines.append("")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check", action="store_true", help="exit 1 if PROGRESS.md would change"
    )
    ap.add_argument("--write", action="store_true", help="write PROGRESS.md (default)")
    args = ap.parse_args()
    if not args.check:
        args.write = True

    text = render(load_packs())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(
                "PROGRESS.md is stale; run: python tools/progress.py --write",
                file=sys.stderr,
            )
            sys.exit(1)
        print("PROGRESS.md up to date")
        return

    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
